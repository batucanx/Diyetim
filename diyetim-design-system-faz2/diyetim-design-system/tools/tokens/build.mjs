#!/usr/bin/env node
// Diyetim token build: tokens/*.json + spec/contracts.json + spec/icons.json → CSS, TypeScript, Dart.
// Kullanım: node tools/tokens/build.mjs          (dosyaları yazar)
//           node tools/tokens/build.mjs --check  (diskteki çıktılar kaynakla aynı değilse hata verir)
import { writeFileSync, readFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import {
  ROOT, THEMES, loadSources, resolvedColors, resolvedShadows, foundationValue, entries, camel, pascal, hashOf,
} from './lib.mjs';
import { buildTsIcons, buildDartIcons } from './icons.mjs';
import { buildTsStrings, buildDartStrings } from './strings.mjs';

const src = loadSources();
const colors = resolvedColors(src);
const shadows = resolvedShadows(src);
const F = src.foundation;
const BANNER = 'GENERATED by tools/tokens/build.mjs — DO NOT EDIT. Kaynak: tokens/*.json, spec/contracts.json';

const px = (v) => parseFloat(String(v));
const rem = (v) => `${+(px(v) / 16).toFixed(4)}rem`;
const STYLES = Object.keys(F.typography).filter((k) => !k.startsWith('$'));
const typo = (name) => F.typography[name].$value;
const letter = (v) => (v ? foundationValue(src, v.slice(1, -1)) : '0em');
const isNumeric = (name) => name.startsWith('numeric');

// ---------------- CSS ----------------
function cssShadow(layers) {
  if (!layers.length) return 'none';
  return layers.map((l) => `${l.inset ? 'inset ' : ''}${l.offsetX} ${l.offsetY} ${l.blur} ${l.spread} ${l.color}`).join(', ');
}
function cssTheme(theme) {
  const lines = Object.entries(colors[theme]).map(([n, v]) => `  --color-${n}: ${v};`);
  lines.push(...Object.entries(shadows[theme]).map(([n, v]) => `  --shadow-${n}: ${cssShadow(v)};`));
  lines.push(`  color-scheme: ${theme};`);
  return lines.join('\n');
}
function buildCss() {
  const o = [];
  o.push(`:root,\n[data-theme="light"] {\n${cssTheme('light')}\n}`);
  o.push(`[data-theme="dark"] {\n${cssTheme('dark')}\n}`);
  o.push(`@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${cssTheme('dark').replace(/^/gm, '  ')}\n  }\n}`);
  const f = [];
  for (const [k] of entries(src, 'spacing')) f.push(`  --spacing-${k}: ${foundationValue(src, `spacing.${k}`)};`);
  for (const [k] of entries(src, 'radius')) f.push(`  --radius-${k}: ${foundationValue(src, `radius.${k}`)};`);
  for (const [k] of entries(src, 'border')) f.push(`  --border-${k}: ${foundationValue(src, `border.${k}`)};`);
  for (const [k] of entries(src, 'opacity')) f.push(`  --opacity-${k}: ${foundationValue(src, `opacity.${k}`)};`);
  for (const [k] of entries(src, 'size')) f.push(`  --size-${k}: ${foundationValue(src, `size.${k}`)};`);
  for (const [k] of entries(src, 'z-index')) f.push(`  --z-${k}: ${foundationValue(src, `z-index.${k}`)};`);
  for (const [k, v] of Object.entries(F.icon.size)) f.push(`  --icon-size-${k}: ${v.$value};`);
  f.push(`  --icon-stroke: ${F.icon.stroke.$value};`);
  for (const [k] of Object.entries(F.motion.duration)) f.push(`  --duration-${k}: ${foundationValue(src, `motion.duration.${k}`)};`);
  for (const [k, v] of Object.entries(F.motion.ease)) f.push(`  --ease-${k}: cubic-bezier(${v.$value.join(', ')});`);
  for (const [k, v] of Object.entries(F.layout).filter(([, v]) => v.$value)) f.push(`  --layout-${k}: ${foundationValue(src, `layout.${k}`)};`);
  for (const bp of ['compact', 'medium', 'expanded']) f.push(`  --layout-margin-${bp}: ${foundationValue(src, F.layout.margin[bp].$value.slice(1, -1))};`);
  f.push(`  --font-family-primary: ${F.font.family.primary.$value.map((x) => (x.includes(' ') || x === 'Nunito' ? `"${x}"` : x)).join(', ')};`);
  for (const [k, v] of Object.entries(F.font.weight)) f.push(`  --font-weight-${k}: ${v.$value};`);
  for (const [k, v] of Object.entries(F['line-height'])) f.push(`  --line-height-${k}: ${v.$value};`);
  for (const s of STYLES) {
    const t = typo(s);
    f.push(`  --font-size-${s}: ${rem(t.fontSize[0])};`, `  --line-height-${s}: ${rem(t.lineHeight[0])};`,
      `  --font-weight-${s}: ${t.fontWeight};`, `  --letter-spacing-${s}: ${letter(t.letterSpacing)};`);
  }
  o.push(`:root {\n${f.join('\n')}\n}`);
  const d = STYLES.filter((s) => typo(s).fontSize[0] !== typo(s).fontSize[1] || typo(s).lineHeight[0] !== typo(s).lineHeight[1])
    .flatMap((s) => [`    --font-size-${s}: ${rem(typo(s).fontSize[1])};`, `    --line-height-${s}: ${rem(typo(s).lineHeight[1])};`]);
  o.push(`@media (min-width: ${foundationValue(src, 'breakpoint.expanded')}) {\n  :root {\n${d.join('\n')}\n  }\n}`);
  const zero = Object.keys(F.motion.duration).map((k) => `    --duration-${k}: 0ms;`);
  o.push(`@media (prefers-reduced-motion: reduce) {\n  :root {\n${zero.join('\n')}\n  }\n}`);
  return o.join('\n\n') + '\n';
}

// ---------------- TypeScript ----------------
function buildTs() {
  // Renk ve gölgede camelCase anahtar (textPrimary); ölçeklerde token adının kendisi (2xl, md).
  const v = (prefix, names, key = camel) => `{\n${names.map((n) => `  ${JSON.stringify(key(n))}: 'var(--${prefix}-${n})',`).join('\n')}\n} as const`;
  const same = (n) => n;
  const o = [];
  o.push(`export const color = ${v('color', Object.keys(colors.light))};`);
  o.push(`export type ColorToken = keyof typeof color;`);
  o.push(`export const shadow = ${v('shadow', Object.keys(shadows.light))};`);
  o.push(`export const spacing = ${v('spacing', entries(src, 'spacing').map(([k]) => k), same)};`);
  o.push(`export type SpacingToken = keyof typeof spacing;`);
  o.push(`export const radius = ${v('radius', entries(src, 'radius').map(([k]) => k), same)};`);
  o.push(`export type RadiusToken = keyof typeof radius;`);
  o.push(`export const size = ${v('size', entries(src, 'size').map(([k]) => k), same)};`);
  o.push(`export const duration = ${v('duration', Object.keys(F.motion.duration), same)};`);
  o.push(`export const ease = ${v('ease', Object.keys(F.motion.ease), same)};`);
  o.push(`export const textStyles = ${JSON.stringify(STYLES)} as const;`);
  o.push(`export type TextStyleName = (typeof textStyles)[number];`);
  o.push(`/** Çözülmüş değerler: testler ve tasarım araçları için. Component'ler var(--…) kullanır. */\nexport const resolvedColors = ${JSON.stringify(colors, null, 2)} as const;`);
  o.push(`export const breakpoints = ${JSON.stringify(Object.fromEntries(entries(src, 'breakpoint').map(([k]) => [k, px(foundationValue(src, `breakpoint.${k}`))])))} as const;`);
  return o.join('\n\n') + '\n';
}

function buildTsContracts() {
  const o = [];
  const st = src.contracts.statusStyles;
  o.push(`/** Durum tonları (Tag, SourceTag zemini/metni). */\nexport const StatusTone = ${JSON.stringify(src.contracts.statusTones)} as const;\nexport type StatusTone = (typeof StatusTone)[number];`);
  for (const [name, def] of Object.entries(src.contracts.enums)) {
    o.push(`/** ${def.doc} */\nexport const ${name} = ${JSON.stringify(def.values)} as const;\nexport type ${name} = (typeof ${name})[number];`);
  }
  for (const [name, map] of Object.entries(st)) {
    if (name.startsWith('$')) continue;
    const lc = name[0].toLowerCase() + name.slice(1);
    const rows = Object.entries(map).map(([k, [tone, icon]]) => `  ${JSON.stringify(k)}: { tone: '${tone}', icon: '${icon}', i18nKey: '${lc}.${k}' },`);
    o.push(`export const ${lc}Styles: Record<${name}, { tone: StatusTone; icon: string; i18nKey: string }> = {\n${rows.join('\n')}\n};`);
  }
  return o.join('\n\n') + '\n';
}

// ---------------- Dart ----------------
const dartColor = (hex) => `Color(0x${(hex.length === 7 ? 'FF' + hex.slice(1) : hex.slice(7) + hex.slice(1, 7)).toUpperCase()})`;
const dartNum = (n) => (Number.isInteger(n) ? `${n}.0` : `${n}`);

function buildDartPalette() {
  const o = [`import 'dart:ui' show Color;`, '', '/// Primitive renk rampaları. Component\'ler bu sınıfı doğrudan kullanmaz; [DyColors] üzerinden okur.', 'abstract final class DyPalette {'];
  for (const [fam, ramp] of Object.entries(src.primitive.color)) {
    for (const [step, t] of Object.entries(ramp)) o.push(`  static const ${camel(fam)}${step} = ${dartColor(t.$value)};`);
  }
  o.push('}');
  return o.join('\n') + '\n';
}

function buildDartColors() {
  const names = Object.keys(colors.light);
  const f = names.map(camel);
  const o = [`import 'package:flutter/material.dart';`, '', '/// Semantic renkler. `Theme.of(context).extension<DyColors>()!` veya `context.dy.colors` ile okunur.',
    '@immutable', 'class DyColors extends ThemeExtension<DyColors> {', '  const DyColors({'];
  o.push(...f.map((n) => `    required this.${n},`), '  });', '');
  names.forEach((n, i) => o.push(`  final Color ${f[i]};`));
  for (const theme of THEMES) {
    o.push('', `  static const ${theme} = DyColors(`);
    names.forEach((n, i) => o.push(`    ${f[i]}: ${dartColor(colors[theme][n])},`));
    o.push('  );');
  }
  o.push('', '  @override', '  DyColors copyWith({', ...f.map((n) => `    Color? ${n},`), '  }) {', '    return DyColors(',
    ...f.map((n) => `      ${n}: ${n} ?? this.${n},`), '    );', '  }', '',
    '  @override', '  DyColors lerp(covariant ThemeExtension<DyColors>? other, double t) {', '    if (other is! DyColors) return this;', '    return DyColors(',
    ...f.map((n) => `      ${n}: Color.lerp(${n}, other.${n}, t)!,`), '    );', '  }', '}');
  return o.join('\n') + '\n';
}

function buildDartShadows() {
  const dartShadow = (l) => `BoxShadow(offset: Offset(${dartNum(px(l.offsetX))}, ${dartNum(px(l.offsetY))}), blurRadius: ${dartNum(px(l.blur))}, spreadRadius: ${dartNum(px(l.spread))}, color: ${dartColor(l.color)})`;
  const levels = Object.keys(shadows.light);
  const o = [`import 'package:flutter/material.dart';`, '', '/// Derinlik. Dark temada iç kenar ışığı (inset) Flutter\'da [edgeHighlight] olarak ayrı verilir; kenarlık olarak çizilir.',
    '@immutable', 'class DyShadows extends ThemeExtension<DyShadows> {', '  const DyShadows({', ...levels.map((l) => `    required this.${l},`), '    required this.edgeHighlight,', '  });', '',
    ...levels.map((l) => `  final List<BoxShadow> ${l};`), '', '  /// Dark temada yükseltilmiş yüzeylerin üst kenar ışığı; light temada şeffaf.', '  final Color edgeHighlight;'];
  for (const theme of THEMES) {
    o.push('', `  static const ${theme} = DyShadows(`);
    let edge = '#00000000';
    for (const l of levels) {
      const outer = shadows[theme][l].filter((x) => !x.inset);
      const inset = shadows[theme][l].find((x) => x.inset);
      if (inset && l === 'low') edge = inset.color;
      o.push(`    ${l}: [${outer.map(dartShadow).join(', ')}],`);
    }
    o.push(`    edgeHighlight: ${dartColor(edge)},`, '  );');
  }
  o.push('', '  List<BoxShadow> of(DyElevation e) => switch (e) {', ...levels.map((l) => `        DyElevation.${l} => ${l},`), '      };', '',
    '  @override', '  DyShadows copyWith() => this;', '', '  @override',
    '  DyShadows lerp(covariant ThemeExtension<DyShadows>? other, double t) {', '    if (other is! DyShadows) return this;', '    return t < 0.5 ? this : other;', '  }', '}');
  o.unshift(`import 'dy_contracts.g.dart';`);
  return o.join('\n') + '\n';
}

function buildDartFoundation() {
  const o = [`import 'package:flutter/animation.dart';`, ''];
  const block = (cls, doc, pairs) => {
    o.push(`/// ${doc}`, `abstract final class ${cls} {`, ...pairs.map(([n, v]) => `  static const ${n} = ${v};`), '}', '');
  };
  const key = (k) => (k === '0' ? 'none' : k === '2xs' ? 'xxs' : k.replace(/^(\d)xl$/, 'xl$1'));
  block('DySpacing', 'Boşluk ölçeği (4 pt taban). Ham sayı yerine bunlar kullanılır.', entries(src, 'spacing').map(([k]) => [key(k), dartNum(px(foundationValue(src, `spacing.${k}`)))]));
  block('DyRadius', 'Köşe yarıçapları.', entries(src, 'radius').map(([k]) => [key(k), dartNum(px(foundationValue(src, `radius.${k}`)))]));
  block('DySize', 'Sabit ölçüler ve dokunma hedefleri.', entries(src, 'size').map(([k]) => [camel(k), dartNum(px(foundationValue(src, `size.${k}`)))]));
  block('DyIconSize', 'İkon boyutları.', Object.entries(F.icon.size).map(([k, v]) => [k, dartNum(px(v.$value))]).concat([['stroke', dartNum(F.icon.stroke.$value)]]));
  block('DyBorderWidth', 'Kenarlık kalınlıkları.', entries(src, 'border').map(([k]) => [camel(k), dartNum(px(foundationValue(src, `border.${k}`)))]));
  block('DyOpacity', 'Opaklık değerleri.', entries(src, 'opacity').map(([k]) => [camel(k), dartNum(foundationValue(src, `opacity.${k}`))]));
  block('DyBreakpoint', 'Pencere sınıfı eşikleri (mantıksal piksel).', entries(src, 'breakpoint').map(([k]) => [k, dartNum(px(foundationValue(src, `breakpoint.${k}`)))]));
  block('DyDuration', 'Hareket süreleri. Hareketi azalt açıkken DyMotion.of(context) sıfırlar.', Object.keys(F.motion.duration).map((k) => [k, `Duration(milliseconds: ${px(foundationValue(src, `motion.duration.${k}`))})`]));
  block('DyEasing', 'Hareket eğrileri.', Object.entries(F.motion.ease).map(([k, v]) => [k, `Cubic(${v.$value.map(dartNum).join(', ')})`]));
  return o.join('\n');
}

function buildDartTypography() {
  const o = [`import 'package:flutter/painting.dart';`, `import 'dy_contracts.g.dart';`, '',
    '/// Tipografi ölçüleri. [compact] mobil, [expanded] masaüstü (≥ DyBreakpoint.expanded).',
    'abstract final class DyTypeScale {', `  static const fontFamily = '${F.font.family.primary.$value[0]}';`, '', '  /// Font dosyaları dy_tokens paketindedir (fonts/); uygulama pubspec\'ine ayrıca eklenmez.', `  static const fontPackage = 'dy_tokens';`, ''];
  for (const [mode, i] of [['compact', 0], ['expanded', 1]]) {
    o.push(`  static TextStyle ${mode}(DyTextStyle style) => switch (style) {`);
    for (const s of STYLES) {
      const t = typo(s);
      const fs = px(t.fontSize[i]); const lh = px(t.lineHeight[i]);
      const ls = letter(t.letterSpacing); const lsPx = ls.endsWith('em') ? +(parseFloat(ls) * fs).toFixed(3) : px(ls);
      const feat = isNumeric(s) ? `, fontFeatures: [FontFeature.tabularFigures()]` : '';
      o.push(`        DyTextStyle.${camel(s)} => const TextStyle(fontFamily: fontFamily, package: fontPackage, fontSize: ${dartNum(fs)}, height: ${+(lh / fs).toFixed(4)}, fontWeight: FontWeight.w${t.fontWeight}, letterSpacing: ${dartNum(lsPx)}${feat}, leadingDistribution: TextLeadingDistribution.even),`);
    }
    o.push('      };', '');
  }
  o.push('}');
  return o.join('\n') + '\n';
}

function buildDartContracts() {
  const o = ['/// Durum tonları (Tag, SourceTag).', `enum DyStatusTone { ${src.contracts.statusTones.join(', ')} }`, ''];
  for (const [name, def] of Object.entries(src.contracts.enums)) {
    const dartName = name === 'TextStyleToken' ? 'DyTextStyle' : `Dy${name}`;
    o.push(`/// ${def.doc}`, `enum ${dartName} {`, ...def.values.map((v) => `  ${camel(v)}('${v}'),`), '  ;', '', `  const ${dartName}(this.wire);`, '', '  /// Platformlar arası ortak ad (spec/contracts.json).', '  final String wire;', '}', '');
  }
  o.push('/// Durumun görsel karşılığı. Metin, çeviri anahtarı [i18nKey] ile gelir.', 'class DyStatusStyle {', '  const DyStatusStyle(this.tone, this.icon, this.i18nKey);', '  final DyStatusTone tone;', '', '  /// DyIcons içindeki ikon adı.', '  final String icon;', '  final String i18nKey;', '}', '');
  for (const [name, map] of Object.entries(src.contracts.statusStyles)) {
    if (name.startsWith('$')) continue;
    const lc = name[0].toLowerCase() + name.slice(1);
    o.push(`extension Dy${name}Style on Dy${name} {`, '  DyStatusStyle get style => switch (this) {', ...Object.entries(map).map(([k, [tone, icon]]) => `        Dy${name}.${camel(k)} => const DyStatusStyle(DyStatusTone.${tone}, '${icon}', '${lc}.${k}'),`), '      };', '}', '');
  }
  return o.join('\n');
}

// ---------------- yazma / kontrol ----------------
function withHeader(path, body) {
  const c = path.endsWith('.css') ? ['/*', ' */'] : ['//', ''];
  const head = path.endsWith('.css') ? `/* ${BANNER}\n * hash: ${hashOf(body)}\n */\n` : `// ${BANNER}\n// hash: ${hashOf(body)}\n// ignore_for_file: type=lint\n`;
  if (path.endsWith('.json')) return body;
  if (path.endsWith('.ts')) return `// ${BANNER}\n// hash: ${hashOf(body)}\n/* eslint-disable */\n` + body;
  void c;
  return head + body;
}

const WEB = 'packages/web/tokens/src/generated';
const DART = 'packages/flutter/dy_tokens/lib/src/generated';
const outputs = {
  [`${WEB}/tokens.css`]: buildCss(),
  [`${WEB}/tokens.ts`]: buildTs(),
  [`${WEB}/contracts.ts`]: buildTsContracts(),
  [`${WEB}/resolved.json`]: JSON.stringify({ colors, shadows }, null, 2) + '\n',
  [`${DART}/dy_palette.g.dart`]: buildDartPalette(),
  [`${DART}/dy_colors.g.dart`]: buildDartColors(),
  [`${DART}/dy_shadows.g.dart`]: buildDartShadows(),
  [`${DART}/dy_foundation.g.dart`]: buildDartFoundation(),
  [`${DART}/dy_typography.g.dart`]: buildDartTypography(),
  [`${DART}/dy_contracts.g.dart`]: buildDartContracts(),
  [`${DART}/resolved.json`]: JSON.stringify({ colors }, null, 2) + '\n',
  ['packages/web/ui/src/generated/icons.ts']: buildTsIcons(),
  ['packages/flutter/dy_ui/lib/src/generated/dy_icons.g.dart']: buildDartIcons(),
  ['packages/web/ui/src/generated/strings.ts']: buildTsStrings(),
  ['packages/flutter/dy_ui/lib/src/generated/dy_strings.g.dart']: buildDartStrings(),
};

const check = process.argv.includes('--check');
let stale = [];
for (const [rel, body] of Object.entries(outputs)) {
  const file = join(ROOT, rel);
  const content = withHeader(rel, body);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) stale.push(rel);
  } else {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, content);
  }
}
if (check) {
  if (stale.length) {
    console.error(`Üretilmiş token dosyaları kaynakla uyuşmuyor (elle düzenlenmiş ya da build çalıştırılmamış):\n  ${stale.join('\n  ')}\nÇözüm: pnpm tokens:build`);
    process.exit(1);
  }
  console.log(`tokens:check — ${Object.keys(outputs).length} üretilmiş dosya kaynakla aynı.`);
} else {
  console.log(`tokens:build — ${Object.keys(outputs).length} dosya yazıldı.`);
}
